"""Z3 SMT Solver interface and formal verification engine for CIN-IR.

Provides:
- Bidirectional translation between CIN-IR and Z3 AST expressions.
- Counterexample extraction (sat model) and unbounded domain proof (unsat).
- Formal verification against SyGuS specifications across all Z^k.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable

try:
    import z3

    HAS_Z3 = True
except ImportError:
    z3 = None
    HAS_Z3 = False

PROOF_SCOPE_Z3 = "cin.verifier/z3-smt-lia-v0.1"


@dataclass(frozen=True)
class Z3Verdict:
    """Formal verification verdict generated by Z3 SMT solver."""

    status: str  # "SYMBOLIC_PROVED", "COUNTEREXAMPLE", "UNKNOWN"
    proof_scope: str
    counterexample: tuple[int, ...] | None = None
    explanation: str = ""
    solver_time_ms: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "proof_scope": self.proof_scope,
            "counterexample": self.counterexample,
            "explanation": self.explanation,
            "solver_time_ms": self.solver_time_ms,
        }


def cin_to_z3(node: dict, z3_vars: list[Any]) -> Any:
    """Recursively converts a closed CIN-IR node to a Z3 expression.

    Args:
        node: CIN-IR dictionary.
        z3_vars: List of Z3 Int variables corresponding to Arg(0)..Arg(k-1).

    Returns:
        Z3 ExprRef.
    """
    if not HAS_Z3:
        raise RuntimeError("z3-solver is not installed in the environment")

    op = node.get("op")

    if op == "Arg":
        idx = node["index"]
        if not 0 <= idx < len(z3_vars):
            raise ValueError(f"Arg index {idx} out of range for arity {len(z3_vars)}")
        return z3_vars[idx]

    if op == "ConstInt":
        return z3.IntVal(node["value"])

    args = node.get("args", [])

    if op == "Add":
        return cin_to_z3(args[0], z3_vars) + cin_to_z3(args[1], z3_vars)

    if op == "Sub":
        return cin_to_z3(args[0], z3_vars) - cin_to_z3(args[1], z3_vars)

    if op == "LessThan":
        return cin_to_z3(args[0], z3_vars) < cin_to_z3(args[1], z3_vars)

    if op == "Equal":
        return cin_to_z3(args[0], z3_vars) == cin_to_z3(args[1], z3_vars)

    if op == "If":
        cond = cin_to_z3(args[0], z3_vars)
        then_val = cin_to_z3(args[1], z3_vars)
        else_val = cin_to_z3(args[2], z3_vars)
        return z3.If(cond, then_val, else_val)

    raise ValueError(f"Unsupported CIN-IR operator for Z3 conversion: {op}")


def verify_spec_with_z3(
    program: dict,
    spec_predicate: Callable[[list[Any], Any], Any],
    arity: int,
    var_names: list[str] | None = None,
    precondition: Callable[[list[Any]], Any] | None = None,
    timeout_ms: int = 5000,
) -> Z3Verdict:
    """Verifies a program AST against a formal mathematical specification over all Z^k.

    Checks satisfiability of:
        precondition(vars) AND NOT spec_predicate(vars, P(vars))

    If UNSAT => Program is mathematically proven correct for all inputs in Z^k.
    If SAT   => Counterexample model found.
    """
    if not HAS_Z3:
        return Z3Verdict(
            status="UNKNOWN",
            proof_scope=PROOF_SCOPE_Z3,
            explanation="z3-solver is not available",
        )

    names = var_names or [f"x_{i}" for i in range(arity)]
    z3_vars = [z3.Int(names[i]) for i in range(arity)]

    try:
        z3_prog = cin_to_z3(program, z3_vars)
    except Exception as e:
        return Z3Verdict(
            status="UNKNOWN",
            proof_scope=PROOF_SCOPE_Z3,
            explanation=f"Z3 AST translation error: {e}",
        )

    solver = z3.Solver()
    solver.set("timeout", timeout_ms)

    if precondition is not None:
        solver.add(precondition(z3_vars))

    # We want to find a counterexample: precondition AND NOT postcondition
    post = spec_predicate(z3_vars, z3_prog)
    solver.add(z3.Not(post))

    check_res = solver.check()

    if check_res == z3.unsat:
        return Z3Verdict(
            status="SYMBOLIC_PROVED",
            proof_scope=PROOF_SCOPE_Z3,
            explanation=f"Universally proved correct over all Z^{arity} by Z3 SMT solver.",
        )

    if check_res == z3.sat:
        model = solver.model()
        ce_point = tuple(
            model.eval(z3_vars[i], model_completion=True).as_long() for i in range(arity)
        )
        return Z3Verdict(
            status="COUNTEREXAMPLE",
            proof_scope=PROOF_SCOPE_Z3,
            counterexample=ce_point,
            explanation=f"Z3 found counterexample at {ce_point}",
        )

    return Z3Verdict(
        status="UNKNOWN",
        proof_scope=PROOF_SCOPE_Z3,
        explanation=f"Z3 solver returned {check_res}",
    )


def verify_equivalence_with_z3(
    prog1: dict,
    prog2: dict,
    arity: int,
    timeout_ms: int = 5000,
) -> Z3Verdict:
    """Formally proves whether prog1(x) == prog2(x) for all x in Z^k using Z3."""
    if not HAS_Z3:
        return Z3Verdict(
            status="UNKNOWN",
            proof_scope=PROOF_SCOPE_Z3,
            explanation="z3-solver is not available",
        )

    z3_vars = [z3.Int(f"x_{i}") for i in range(arity)]

    try:
        z1 = cin_to_z3(prog1, z3_vars)
        z2 = cin_to_z3(prog2, z3_vars)
    except Exception as e:
        return Z3Verdict(
            status="UNKNOWN",
            proof_scope=PROOF_SCOPE_Z3,
            explanation=f"Z3 translation error: {e}",
        )

    solver = z3.Solver()
    solver.set("timeout", timeout_ms)
    solver.add(z1 != z2)

    check_res = solver.check()
    if check_res == z3.unsat:
        return Z3Verdict(
            status="SYMBOLIC_PROVED",
            proof_scope=PROOF_SCOPE_Z3,
            explanation="Programs are universally equivalent over all Z^k.",
        )

    if check_res == z3.sat:
        model = solver.model()
        ce_point = tuple(
            model.eval(z3_vars[i], model_completion=True).as_long() for i in range(arity)
        )
        return Z3Verdict(
            status="COUNTEREXAMPLE",
            proof_scope=PROOF_SCOPE_Z3,
            counterexample=ce_point,
            explanation=f"Programs disagree at {ce_point}",
        )

    return Z3Verdict(
        status="UNKNOWN",
        proof_scope=PROOF_SCOPE_Z3,
        explanation=f"Z3 solver returned {check_res}",
    )
